"""
Model benchmark harness.

Trains the churn and engagement models on two datasets and prints them side by side:

  1. `data/sample/user_data_sample.csv`    - the original sample, where `lifecycle_stage`
                                             is drawn independently of behaviour, so no
                                             signal exists to find.
  2. `data/sample/user_data_benchmark.csv` - generated by `src/utils/data_generator.py`
                                             from an explicit latent-variable process,
                                             so the true structure is known.

Reading the two together is what makes either one interpretable. Near-chance scores on
(1) plus strong scores on (2) demonstrate that the pipeline is correct *and* that its
leakage guard is working. Strong scores on both would mean the guard has a hole.

Usage:
    python scripts/benchmark_models.py
    python scripts/benchmark_models.py --output data/output/model_benchmark.csv
"""

from __future__ import annotations

import argparse
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from src.intelligence.data_ingestion import DataIngestionEngine  # noqa: E402
from src.intelligence.ml_propensity_models import PropensityModelEngine  # noqa: E402
from src.utils.data_generator import (  # noqa: E402
    bayes_optimal_churn_auc,
    bayes_optimal_engagement_r2,
    generate_user_data,
)


BENCHMARK_PATH = "data/sample/user_data_benchmark.csv"
SAMPLE_PATH = "data/sample/user_data_sample.csv"


def _evaluate(path: str, label: str) -> dict:
    """Run a dataset through the real ingestion path so features match the pipeline."""
    ingestion = DataIngestionEngine()
    df = ingestion.load_and_validate(path)
    df = ingestion.engineer_features(df)

    models = PropensityModelEngine(random_state=42, schema_map=ingestion.schema_map)
    _, churn_metrics = models.train_churn_model(df)
    _, engagement_metrics = models.train_engagement_model(df)

    return {
        "dataset": label,
        "n_users": len(df),
        "churn_auc": round(churn_metrics.get("auc_test", float("nan")), 4),
        "churn_cv_auc": round(churn_metrics.get("auc_cv_mean", float("nan")), 4),
        "engagement_r2": round(engagement_metrics.get("r2_score", float("nan")), 4),
        "engagement_rmse": round(engagement_metrics.get("rmse", float("nan")), 4),
    }


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Benchmark models on signal-free vs known-signal data"
    )
    parser.add_argument("--output", default="data/output/model_benchmark.csv")
    parser.add_argument("--n-users", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args(argv)

    if not os.path.exists(BENCHMARK_PATH):
        print(f"[..] {BENCHMARK_PATH} missing; generating it")
        generate_user_data(n_users=args.n_users, seed=args.seed).to_csv(
            BENCHMARK_PATH, index=False
        )

    rows = []
    for path, label in (
        (SAMPLE_PATH, "original_sample (no signal by construction)"),
        (BENCHMARK_PATH, "ground_truth_benchmark (known DGP)"),
    ):
        if not os.path.exists(path):
            print(f"[!!] skipping missing dataset: {path}")
            continue
        print("\n" + "=" * 78)
        print(f"BENCHMARKING: {label}")
        print("=" * 78)
        rows.append(_evaluate(path, label))

    results = pd.DataFrame(rows)
    auc_ceiling = bayes_optimal_churn_auc()
    r2_ceiling = bayes_optimal_engagement_r2()

    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    results.assign(
        bayes_optimal_churn_auc=round(auc_ceiling, 4),
        bayes_optimal_engagement_r2=round(r2_ceiling, 4),
    ).to_csv(args.output, index=False)

    print("\n" + "=" * 78)
    print("BENCHMARK SUMMARY")
    print("=" * 78)
    print(results.to_string(index=False))

    bench = next((r for r in rows if r["dataset"].startswith("ground_truth")), None)
    print("\nOracle ceilings for the benchmark DGP.")
    print("These are what a model that knew each user's *latent* traits exactly would score;")
    print("observable columns are only noisy reflections of those latents, so real models")
    print("sit below the ceiling by construction. Labels are sampled, never deterministic.")
    print(f"  churn AUC     oracle {auc_ceiling:.3f}", end="")
    if bench:
        print(f"   | model {bench['churn_auc']:.3f}"
              f"   ({bench['churn_auc'] / auc_ceiling:.0%} of oracle)")
    else:
        print()
    print(f"  engagement R2 oracle {r2_ceiling:.3f}", end="")
    if bench:
        print(f"   | model {bench['engagement_r2']:.3f}"
              f"   ({bench['engagement_r2'] / r2_ceiling:.0%} of oracle)")
    else:
        print()
    print(f"\n[OK] Saved: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
